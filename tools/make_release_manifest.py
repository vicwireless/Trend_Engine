def description(p: dict) -> str:
    lines = [p["intro"], "", "WHAT YOU GET"] + [f"• {g}" for g in p["get"]]
    lines += ["", "Print at 100% / \"Actual size\". Matte cardstock (65-110 lb) is best for writing on. "
              "It's mostly white space, so it's light on ink.", "", COMMON]
    return "\n".join(lines)


def op(name: str, payload: dict) -> dict:
    return {"op": name, "niche": NICHE, "payload": payload, "payload_sha256": payload_sha256(payload)}


def main() -> None:
    today = dt.date(2026, 10, 23)
    snap = {"as_of": today.isoformat(), "kind": "product_costs", "verified": True,
            "source": "Engine decision 2026-10-23: planner-family printables are generated by code (tools/make_planner_family.py); "
                      "no per-unit production cost. Etsy fees come from the channel-fees snapshot.",
            "items": {"digital": {"unit_cost_usd": 0.0, "shipping_usd": 0.0}}}
    (ROOT / SNAPSHOT).write_text(json.dumps(snap, indent=2) + "\n", encoding="utf-8")

    ops = []
    for p in PRODUCTS:
        base = f"{ASSETS}/{p['key']}"
        idx = len(ops)
        ops.append(op("etsy_create_digital_listing", {
            "title": p["title"], "description": description(p), "tags": p["tags"],
            "taxonomy_id": TAXONOMY_PLANNER_TEMPLATES, "who_made": "i_did", "when_made": "2020_2026",
            "ai_assisted": True, "price_usd": p["price"], "cost_snapshot": SNAPSHOT, "cost_key": "digital"}))
        ref = f"$ref:ops[{idx}].listing_id"
        for name in (f"2027-{p['key']}-letter.pdf", f"2027-{p['key']}-a4.pdf", f"2027-{p['key']}-how-to-print.pdf"):
            ops.append(op("etsy_upload_file", {"listing_id": ref, "path": f"{base}/{name}",
                                               "file_sha256": file_sha256(ROOT / base / name), "name": name}))
        for rank, kind in enumerate(["1-cover", "2-inside", "3-pages", "4-sizes", "5-print"], start=1):
            rel = f"{base}/images/{p['key']}-{kind}.png"
            ops.append(op("etsy_upload_image", {"listing_id": ref, "path": rel, "file_sha256": file_sha256(ROOT / rel),
                                                "rank": rank, "alt_text": p["alt"] if rank in (1, 3) else
                                                f"{p['title'].split(',')[0]}: {kind.split('-', 1)[1]} image"}))

    manifest = {
        "manifest_id": MANIFEST_ID, "created_at": "2026-10-23T16:40:00Z", "created_by": "claude",
        "summary": "First release: three 2027 planner-family printables (weekly planner, goal planner, habit tracker) "
                   "for the New Year planner window, created as Etsy DRAFTS. Owner ticks the AI-generator field and publishes each.",
        "owner_minutes_estimate": 45, "ops": ops}
    out = ROOT / "releases" / f"{MANIFEST_ID}.yaml"
    out.write_text(yaml.safe_dump(manifest, sort_keys=False, width=120, allow_unicode=True), encoding="utf-8")
    print(out, len(ops), "ops")


if __name__ == "__main__":
    main()
